test_that("designs contain every treatment the right number of times", {
  set.seed(1)
  d <- quiet(des.crd(5, 3))
  expect_equal(as.vector(table(d$Book$treat)), rep(3, 5))
  d <- quiet(des.rbd(4, 3))
  expect_true(all(apply(d$Design, 2, function(b) length(unique(b)) == 4)))
  d <- quiet(des.fat2.crd(3, 2, 2))
  expect_equal(nrow(d$Book), 12)
  expect_equal(as.vector(table(d$Book$factor1, d$Book$factor2)), rep(2, 6))
  d <- quiet(des.fat2.rbd(12, 2, 2))
  expect_equal(as.vector(table(d$Book$factor1, d$Book$factor2)), rep(2, 24))
  d <- quiet(des.sp.crd(11, 3, 2))
  expect_equal(nrow(d$Book), 11 * 3 * 2)
  expect_equal(as.vector(table(d$Book$factor1, d$Book$factor2)), rep(2, 33))
  d <- quiet(des.sp.rbd(3, 4, 3))
  expect_equal(as.vector(table(d$Book$Block, d$Book$factor1)), rep(4, 9))
  expect_error(des.crd(1, 3))
})
